#!/usr/bin/env node
// mockup-autoopen — PostToolUse hook for Write.
//
// Does the UI_MOCKUPS.md rule instead of reminding about it: when a mockup HTML
// file is written, regenerate the master jump list (.mockups/_index.html) and pop
// the new mockup in the browser. See docs/UI_MOCKUPS.md "ALWAYS: pop it in Chrome
// + keep a master index".
//
// Debounce: a /design run writes 4 mockups in one burst (8 before 2026-08-18).
// Four Chrome tabs is a bug, not a feature — so the `open` fires at most once per OPEN_WINDOW_MS, marked
// by a stamp file in the .mockups dir. The index is regenerated on EVERY write,
// because that is cheap and always wanted.
//
// Convenience only: always exits 0, never affects the tool result, never throws.
//
// Test/CI seams:
//   CLAUDE_MOCKUP_OPEN_CMD — command used instead of `open` (tests point it at a
//                            harmless script; also lets non-mac users wire xdg-open)
//   CLAUDE_MOCKUP_NO_OPEN=1 — regenerate the index, never launch anything

const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

const OPEN_WINDOW_MS = 20_000;
const STAMP = '.autoopen-stamp';
const INDEX = '_index.html';

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// The .mockups root for a file living under one (handles nested groups like
// .mockups/design-slug/v3.html).
function mockupsRoot(file) {
  const parts = file.split(path.sep);
  const i = parts.indexOf('.mockups');
  if (i === -1) return null;
  return parts.slice(0, i + 1).join(path.sep);
}

function listHtml(dir, root, out) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      listHtml(full, root, out);
    } else if (e.isFile() && e.name.endsWith('.html') && e.name !== INDEX) {
      let mtime = 0;
      try {
        mtime = fs.statSync(full).mtimeMs;
      } catch {
        continue;
      }
      out.push({ full, rel: path.relative(root, full), mtime, label: variantLabel(full) });
    }
  }
  return out;
}

// `<!-- VARIANT: v3 — bento grid -->` header comment, when present.
function variantLabel(file) {
  try {
    const fd = fs.openSync(file, 'r');
    const buf = Buffer.alloc(4096);
    const n = fs.readSync(fd, buf, 0, 4096, 0);
    fs.closeSync(fd);
    const m = buf.toString('utf8', 0, n).match(/<!--\s*VARIANT:\s*([^]*?)-->/i);
    return m ? m[1].trim().replace(/\s+/g, ' ') : null;
  } catch {
    return null;
  }
}

function writeIndex(root) {
  const files = listHtml(root, root, []).sort((a, b) => b.mtime - a.mtime); // newest first
  const rows = files
    .map(
      (f) =>
        `<li><a href="${esc(f.rel)}">${esc(f.label || f.rel)}</a>` +
        (f.label ? ` <span class="p">${esc(f.rel)}</span>` : '') +
        `</li>`
    )
    .join('\n');
  const html =
    '<!doctype html>\n<meta charset="utf-8">\n<title>Mockups</title>\n' +
    '<style>body{font:16px/1.6 system-ui;margin:2rem;max-width:60rem}' +
    'li{margin:.25rem 0}.p{color:#888;font-size:.8em}</style>\n' +
    '<h1>Mockups</h1>\n<p>Newest first. Generated by hooks/mockup-autoopen.js.</p>\n' +
    (rows ? `<ul>\n${rows}\n</ul>\n` : '<p>No mockups yet.</p>\n');
  fs.writeFileSync(path.join(root, INDEX), html);
}

function maybeOpen(root, file) {
  if (process.env.CLAUDE_MOCKUP_NO_OPEN === '1') return;

  const cmd = process.env.CLAUDE_MOCKUP_OPEN_CMD || (process.platform === 'darwin' ? 'open' : null);
  if (!cmd) return; // no `open` off macOS — index only, silently

  const stamp = path.join(root, STAMP);
  try {
    const age = Date.now() - fs.statSync(stamp).mtimeMs;
    if (age >= 0 && age < OPEN_WINDOW_MS) return; // same burst — already popped one
  } catch {
    // no stamp yet -> first open
  }
  try {
    fs.writeFileSync(stamp, String(Date.now()));
  } catch {
    /* unwritable dir: still try to open */
  }

  const child = spawn(cmd, [file], { detached: true, stdio: 'ignore' });
  child.on('error', () => {}); // `open` missing -> silent
  child.unref();
}

function main() {
  let payload = {};
  try {
    const raw = fs.readFileSync(0, 'utf8');
    if (raw.trim()) payload = JSON.parse(raw);
  } catch {
    return;
  }

  const input = payload.tool_input || payload.toolInput;
  if (!input || typeof input !== 'object') return;
  let file = input.file_path || input.path;
  if (!file || typeof file !== 'string') return;

  file = path.resolve(payload.cwd ? path.resolve(payload.cwd, file) : file);

  if (!file.endsWith('.html')) return;
  if (path.basename(file) === INDEX) return; // don't recurse on our own output

  const root = mockupsRoot(file);
  if (!root) return; // not under a .mockups dir
  if (!fs.existsSync(file)) return; // write failed / already gone

  writeIndex(root);
  maybeOpen(root, file);
}

try {
  main();
} catch {
  /* convenience hook: never affect the tool result */
}
process.exit(0);
